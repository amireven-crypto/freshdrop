#!/bin/sh
# Concatenate the stylesheets into one render-blocking file (QA 15 Nov: 7 -> 1).
# Edit the source files, then run: sh scripts/build-css.sh
set -eu
cd "$(dirname "$0")/../assets"
{ echo "/* fd.css – generated by scripts/build-css.sh from style, features, extras, cattitles, advideo, auth, leeward. Do not edit by hand. */"
  for f in style.css features.css extras.css cattitles.css advideo.css auth.css leeward.css; do echo "/* ---- $f ---- */"; cat "$f"; echo; done; } > fd.css
echo "fd.css: $(wc -c < fd.css) bytes"
